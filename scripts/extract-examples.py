#!/usr/bin/env python3
"""Build a standalone document of the main book's examples and their marked solutions.

A worked solution is extracted when it is wrapped in an examplesolution environment after its
example; an example with no worked solution is followed by a "% no solution" comment. Run with
--unmarked to list the examples that have neither, by chapter.
"""

import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
BOOK = ROOT / "book"
EXAMPLE_TOKEN = re.compile(r"\\(begin|end)\s*\{(example|examplesolution)\}(?:\[[^]]*\])?")
NO_SOLUTION = re.compile(r"[ \t]*\n% no solution\b")
FLOAT_PLACEMENT = re.compile(r"\\begin\{(figure|table)\}\[[^]]*\]")
REFERENCE = re.compile(r"\\(eqref|ref)\{([^}]+)\}")


def inputs(path: Path):
    for line in path.read_text().splitlines():
        active = line.split("%", 1)[0]
        yield from re.findall(r"\\input\{([^}]+)\}", active)


def section_paths():
    for chapter_input in inputs(BOOK / "TRENCH_DIFFEQ_BV.tex"):
        if re.fullmatch(r"chapters/\d+/chapter", chapter_input):
            for section_input in inputs(BOOK / f"{chapter_input}.tex"):
                if re.fullmatch(r"chapters/\d+/\d+\.\d+", section_input):
                    yield BOOK / f"{section_input}.tex"


def example_blocks(source: str):
    """Extract balanced example environments within one section.

    Returns (statement, solution, marked) per example: the solution is the examplesolution
    environment that follows the example, if any, and marked says whether the example has either
    a solution or a "% no solution" comment.
    """
    blocks = []
    start = None
    open_kind = None
    for match in EXAMPLE_TOKEN.finditer(source):
        kind = match.group(2)
        if match.group(1) == "begin":
            if open_kind is not None:
                raise ValueError(f"{kind} begins before the previous {open_kind} ends")
            if kind == "examplesolution" and (not blocks or blocks[-1][1] is not None):
                raise ValueError("examplesolution does not follow an example")
            start, open_kind = match.start(), kind
        else:
            if open_kind != kind:
                raise ValueError(f"{kind} ends without a begin")
            block = source[start:match.end()]
            if kind == "example":
                marked = bool(NO_SOLUTION.match(source, match.end()))
                blocks.append([block, None, marked])
            else:
                blocks[-1][1] = block
                blocks[-1][2] = True
            start = open_kind = None
    if open_kind is not None:
        raise ValueError(f"{open_kind} begins without an end")
    return [tuple(block) for block in blocks]


def main():
    examples = []
    for path in section_paths():
        source = path.read_text()
        blocks = example_blocks(source)
        examples.extend((path, *block) for block in blocks)

    unmarked = [(path, statement) for path, statement, _, marked in examples if not marked]
    if "--unmarked" in sys.argv[1:]:
        by_chapter = {}
        for path, statement in unmarked:
            label = re.search(r"\\label\{example:([^}]+)\}", statement)
            by_chapter.setdefault(path.parent.name, []).append(
                label.group(1) if label else f"{path.stem}.(unlabeled)"
            )
        for chapter, labels in by_chapter.items():
            print(f"chapter {chapter}: {len(labels)} unmarked: {' '.join(labels)}")
        return

    text = "\n".join(statement + (solution or "") for _, statement, solution, _ in examples)
    labels = set(re.findall(r"\\label\{([^}]+)\}", text))

    def resolve_external(match):
        command, label = match.groups()
        if label in labels:
            return match.group()
        kind, separator, number = label.partition(":")
        if not separator or not re.fullmatch(r"\d+(?:\.\d+)+", number):
            raise ValueError(f"cannot print external reference {match.group()}")
        if command == "eqref" and kind == "eq":
            return rf"\textup{{({number})}}"
        if command == "ref":
            return number
        raise ValueError(f"cannot print external reference {match.group()}")

    parts = [
        "% Generated by scripts/extract-examples.py from the main book's section inputs.",
        "% Examples are followed by the worked solutions marked with examplesolution in the book.",
        "% Blue text is removed, floats are placed here, and external references retain their",
        "% printed book numbers.",
        r"\input{preamble}",
        r"\hypersetup{allcolors=black}",
        r"\begin{document}",
        "",
        r"\chapter*{All Examples}",
        r"\makeatletter",
        r"\@starttoc{toc}",
        r"\makeatother",
    ]
    previous_section = None
    previous_chapter = None
    section_count = 0
    for path, statement, solution, _ in examples:
        chapter, section = map(int, path.stem.split("."))
        if path != previous_section:
            parts.extend(["", rf"\section*{{Section {chapter}.{section}}}"])
            if chapter != previous_chapter:
                parts.extend(
                    [
                        r"\phantomsection",
                        rf"\addcontentsline{{toc}}{{chapter}}{{Chapter {chapter}}}",
                    ]
                )
                previous_chapter = chapter
            parts.extend(
                [rf"\setcounter{{chapter}}{{{chapter}}}", rf"\setcounter{{section}}{{{section}}}"]
            )
            previous_section = path
            section_count = 0
        first_number = section_count + 1
        block_count = 1
        example_labels = re.findall(r"\\label\{example:(\d+)\.(\d+)\.(\d+)\}", statement)
        for label_chapter, label_section, _ in example_labels:
            if (int(label_chapter), int(label_section)) != (chapter, section):
                raise ValueError(f"example label does not match {path}")
        section_count += block_count
        parts.extend(["", rf"\setcounter{{example}}{{{first_number - 1}}}"])

        # Material between the statement and the solution is skipped, so set the counters for each.
        for block in (statement, solution):
            if block is None:
                continue
            for kind, counter in (("eq", "equation"), ("figure", "figure"), ("table", "table")):
                pattern = rf"\\label\{{{kind}:{chapter}\.{section}\.(\d+)\}}"
                matches = re.findall(pattern, block)
                if matches:
                    parts.append(rf"\setcounter{{{counter}}}{{{int(matches[0]) - 1}}}")
            block = block.replace(r"\color{blue}", r"\relax")
            block = FLOAT_PLACEMENT.sub(lambda match: rf"\begin{{{match.group(1)}}}[H]", block)
            parts.append(REFERENCE.sub(resolve_external, block))

    parts.extend(["", r"\end{document}", ""])
    output = BOOK / "examples.tex"
    output.write_text("\n".join(parts))
    solved = sum(solution is not None for _, _, solution, _ in examples)
    print(
        f"Wrote {len(examples)} examples ({solved} with solutions, {len(unmarked)} unmarked) "
        f"to {output.relative_to(ROOT)}"
    )


if __name__ == "__main__":
    main()
