#!/usr/bin/env python3
"""Build a standalone scratchpad of the main book's numbered theorems."""

import re
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
BOOK = ROOT / "book"
THEOREM = re.compile(r"\\begin\{theorem\}.*?\\end\{theorem\}", re.DOTALL)
THEOREM_LABEL = re.compile(r"\\label\{thmtype:(\d+)\.(\d+)\.(\d+)\}")
EQUATION_LABEL = re.compile(r"\\label\{eq:(\d+)\.(\d+)\.(\d+)\}")
REFERENCE = re.compile(r"\\(eqref|ref|pageref)\{([^}]+)\}")
BLUE_LINE = re.compile(r"(?m)^[ \t]*\\color\{blue\}[ \t]*\n")


def inputs(path: Path):
    """Read active LaTeX input lines, ignoring comments."""
    for line in path.read_text().splitlines():
        active = line.split("%", 1)[0]
        for name in re.findall(r"\\input\{([^}]+)\}", active):
            yield name


def section_paths():
    for chapter_input in inputs(BOOK / "TRENCH_DIFFEQ_BV.tex"):
        if not re.fullmatch(r"chapters/\d+/chapter", chapter_input):
            continue
        for section_input in inputs(BOOK / f"{chapter_input}.tex"):
            if re.fullmatch(r"chapters/\d+/\d+\.\d+", section_input):
                yield BOOK / f"{section_input}.tex"


def main():
    theorems = []
    for path in section_paths():
        source = path.read_text()
        blocks = THEOREM.findall(source)
        if len(blocks) != source.count(r"\begin{theorem}"):
            raise ValueError(f"unmatched theorem environment in {path}")
        theorems.extend((path, block) for block in blocks)

    labels = set(re.findall(r"\\label\{([^}]+)\}", "\n".join(block for _, block in theorems)))

    def resolve_external(match):
        command, label = match.groups()
        if label in labels:
            return match.group()
        kind, separator, number = label.partition(":")
        if not separator or not re.fullmatch(r"\d+(?:\.\d+)+", number) or command == "pageref":
            raise ValueError(f"cannot print external reference {match.group()}")
        if command == "eqref" and kind == "eq":
            return rf"\textup{{({number})}}"
        if command == "ref" and kind in {"eq", "figure", "thmtype"}:
            return number
        raise ValueError(f"cannot print external reference {match.group()}")

    parts = [
        "% Generated by scripts/extract-theorems.py from the main book's section inputs.",
        "% Theorem text is copied except for blue color and references to omitted material.",
        "% External references retain their printed book numbers without links.",
        r"\input{preamble}",
        r"\hypersetup{allcolors=black}",
        r"\begin{document}",
        "",
        r"\chapter*{All Theorems}",
        r"\makeatletter",
        r"\@starttoc{toc}",
        r"\makeatother",
    ]
    previous_section = None
    previous_chapter = None
    for path, block in theorems:
        match = THEOREM_LABEL.search(block)
        if not match:
            raise ValueError(f"missing theorem label in {path}")
        chapter, section, number = map(int, match.groups())
        if f"{chapter}.{section}" != path.stem:
            raise ValueError(f"theorem label does not match {path}")
        if path != previous_section:
            parts.extend(["", rf"\section*{{Section {chapter}.{section}}}"])
            if chapter != previous_chapter:
                parts.extend(
                    [
                        r"\phantomsection",
                        rf"\addcontentsline{{toc}}{{chapter}}{{Chapter {chapter}}}",
                    ]
                )
                previous_chapter = chapter
            parts.extend(
                [rf"\setcounter{{chapter}}{{{chapter}}}", rf"\setcounter{{section}}{{{section}}}"]
            )
            previous_section = path

        parts.extend(["", rf"\setcounter{{theorem}}{{{number - 1}}}"])
        equations = EQUATION_LABEL.findall(block)
        if equations:
            numbers = [int(eq_number) for _, _, eq_number in equations]
            if numbers != list(range(numbers[0], numbers[0] + len(numbers))):
                raise ValueError(f"nonconsecutive equation labels in {path}")
            if any((int(eq_chapter), int(eq_section)) != (chapter, section) for eq_chapter, eq_section, _ in equations):
                raise ValueError(f"equation label does not match {path}")
            parts.append(rf"\setcounter{{equation}}{{{numbers[0] - 1}}}")

        block = BLUE_LINE.sub("", block)
        if r"\color{blue}" in block or r"\textcolor{blue}" in block:
            raise ValueError(f"unhandled blue color in {path}")
        parts.append(REFERENCE.sub(resolve_external, block))

    parts.extend(["", r"\end{document}", ""])
    output = BOOK / "theorems.tex"
    output.write_text("\n".join(parts))
    print(f"Wrote {len(theorems)} theorems to {output.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
